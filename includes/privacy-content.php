    <section id="privacy-1">
        <h3>1. Algemeen</h3>
        <p>Het bestuur van de Fotogroep Windmolenbroek hecht veel waarde aan uw privacy. We vinden het belangrijk dat de Persoonsgegevens die door de Fotogroep Windmolenbroek worden verzameld en verwerkt, zo goed mogelijk worden beschermd.</p>
        <p>Fotogroep Windmolenbroek is verplicht om zorgvuldig en veilig, proportioneel en vertrouwelijk om te gaan met het verzamelen, bewaren en beheren van Persoonsgegevens van Betrokkenen. Dit Privacyreglement is van toepassing op alle Verwerkingen van Persoonsgegevens binnen de Fotogroep Windmolenbroek.</p>
        <p>Voor vragen over dit Reglement of als u een klacht hebt over de manier waarop de Fotogroep Windmolenbroek met uw gegevens omgaat, kunt u contact met ons opnemen. U vindt de contactgegevens op onze website.</p>
    </section>

    <section id="privacy-2">
        <h3>2. Website &amp; Fotobond</h3>
        <p>De Fotogroep Windmolenbroek is aangesloten bij de Fotobond. De Fotogroep Windmolenbroek deelt daarom Persoonsgegevens met de Fotobond-afdeling Twente en de Fotobond via de Fotobond-website. Het privacyreglement van de Fotobond is hierop van toepassing.</p>
        <ul>
            <li>Website Fotogroep Windmolenbroek: <a href="https://www.fotogroep-wmb.nl" rel="noopener noreferrer">https://www.fotogroep-wmb.nl</a></li>
            <li>Verantwoordelijke website: De webmaster van Fotogroep Windmolenbroek.</li>
        </ul>
    </section>

    <section id="privacy-3">
        <h3>3. Doel van het Privacyreglement</h3>
        <p>Dit privacyreglement is een verdieping van het privacybeleid, dat is vastgesteld door het bestuur van Fotogroep Windmolenbroek en beschrijft hoe Fotogroep Windmolenbroek omgaat met de privacy van Betrokkenen.</p>
        <p>Dit privacyreglement kan in de toekomst worden aangepast om bijvoorbeeld aan te sluiten op de geldende wet- en regelgeving of aanpassingen in de werkwijze van de Fotogroep Windmolenbroek.</p>
        <p>Als u deze website bezoekt of lid bent van de Fotogroep Windmolenbroek, kan de vereniging gegevens van u verwerken (bijv. gegevens die u invult op een inschrijfformulier, e-mails via de site, of ledengegevens). Fotogroep Windmolenbroek waarborgt en respecteert uw privacy door naleving van de Algemene Verordening Gegevensbescherming (AVG).</p>
    </section>

