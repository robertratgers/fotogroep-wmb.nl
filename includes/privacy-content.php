    <section id="privacy-5">
        <h3>5. Doeleinden van de Verwerking</h3>
        <p>De Fotogroep Windmolenbroek verzamelt of gebruikt uw Persoonsgegevens alleen voor de volgende doeleinden (Artikel 5 AVG):</p>
        <ul>
            <li>Gebruikelijke activiteiten gelet op de doelstelling (zoals inschrijving voor cursussen en wedstrijden);</li>
            <li>Voorzien van contactinformatie bij deelname aan of organisatie van activiteiten binnen de vereniging;</li>
            <li>Toegang verlenen tot afgeschermde informatie op de website;</li>
            <li>Berekenen, vastleggen en innen van contributies en giften, alsmede ander intern beheer;</li>
            <li>Verzenden van informatie over activiteiten en diensten (nieuwsbrieven, bevestigingen);</li>
            <li>Behandelen van geschillen en controle van de boekhouding;</li>
            <li>Beschikbaar stellen van ledenlijsten en functionarissenlijsten aan de Leden.</li>
        </ul>
    </section>

    <section id="privacy-6">
        <h3>6. Rechtmatige Grondslag</h3>
        <p>Fotogroep Windmolenbroek verwerkt alleen persoonsgegevens op basis van (Artikel 6 AVG):</p>
        <ul>
            <li>Wettelijke verplichtingen;</li>
            <li>Uitvoering van een overeenkomst waarbij de Betrokkene partij is;</li>
            <li>Bestrijding van ernstige gezondheidsbedreigingen (bijv. medische hulp bij evenementen);</li>
            <li>Goede vervulling van de taak van de vereniging;</li>
            <li>Specifieke toestemming van de Betrokkene.</li>
        </ul>
    </section>

    <section id="privacy-7">
        <h3>7. Wijze van Verwerking &amp; Bewaartermijnen</h3>
        <p>Persoonsgegevens van Leden worden uitsluitend verkregen van de Betrokkene zelf, na het verlenen van toestemming. Gegevens worden niet langer bewaard dan noodzakelijk:</p>
        <ul>
            <li>Na beëindiging lidmaatschap: Binnen 6 maanden verwijderd uit de Fotobond-ledenadministratie.</li>
            <li>Zakelijke/financiële relaties of werkzaamheden: Maximaal 2 jaar bewaard na afhandeling, tenzij een wettelijke bewaarplicht langer vereist.</li>
            <li>Historisch archief: Verwijderde gegevens worden geanonimiseerd bewaard voor historisch onderzoek of archivering.</li>
        </ul>
    </section>

    <section id="privacy-8">
        <h3>8. Verwerkte Persoonsgegevens</h3>
        <p>De volgende verplichte en optionele gegevens worden verwerkt via de Fotobond-ledenadministratie:</p>
        <ul>
            <li>Verplicht: Gebruikersnaam, wachtwoord, voornaam, achternaam, e-mailadres, lidnummer, registratiedatum, club, afdeling, ingang/einde lidmaatschap, geboortejaar, geslacht, adres, postcode, woonplaats, telefoonnummer, website, pasfoto/avatar, wedstrijd- en winnende foto’s/filmpjes.</li>
            <li>Optioneel: Bondsonderscheidingen, bijzonderheden over rol/lidmaatschap, jurylid-status, rankingpunten, prestatieonderscheidingen, contributieplicht, actief-status.</li>
        </ul>
    </section>

    <section id="privacy-9">
        <h3>9. Rechten van Betrokkenen</h3>
        <p>Betrokkenen beschikken over de volgende AVG-rechten:</p>
        <ul>
            <li>Recht op informatie &amp; inzage: Weten of en hoe gegevens worden verwerkt.</li>
            <li>Correctierecht: Aanpassen van onjuiste gegevens (Leden kunnen dit zelf op de Fotobond-website).</li>
            <li>Recht van verzet &amp; bezwaar: Verzoeken om stopzetting van gegevensgebruik.</li>
            <li>Recht om vergeten te worden: Verwijdering van persoonsgegevens eisen waar toestemming voor was gegeven.</li>
        </ul>
    </section>

    <section id="privacy-10">
        <h3>10. Cookies &amp; Beveiliging</h3>
        <p>De website van Fotogroep Windmolenbroek en de Fotobond maken gebruik van beveiligingsmaatregelen (zoals versleutelde verbindingen voor inloggegevens) en cookies:</p>
        <ul>
            <li>Functionele cookies: Noodzakelijk voor het inloggen op het ledengedeelte.</li>
            <li>Social Media &amp; Derden cookies: Cookies van Facebook, Google en YouTube voor embedded video’s en functionaliteiten. Deze kunnen via browserinstellingen of adblockers worden geblokkeerd.</li>
        </ul>
    </section>

    <section id="privacy-11">
        <h3>11. Datalekken &amp; Slotbepalingen</h3>
        <p>Inbreuken op de beveiliging van persoonsgegevens (datalekken) met een hoog risico worden gemeld aan de Autoriteit Persoonsgegevens (art. 33 AVG). In gevallen waarin dit reglement niet voorziet, beslist het bestuur. Wijzigingen in dit reglement worden vastgesteld door de Algemene Ledenvergadering (vastgesteld op 8 april 2019).</p>
    </section>
